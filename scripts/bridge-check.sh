#!/usr/bin/env bash
# =============================================================================
#  bridge-check — доходит ли входящая нода до моста (v2)
#
#  Запускать на ВХОДЯЩЕЙ ноде:  bridge-check <IP_МОСТА> [ПОРТ=2087] [SNI]
#
#  Проверяет по шагам и называет причину, а не только "работает / нет":
#    1. открывается ли TCP-порт моста (файрвол моста, слушает ли Xray);
#    2. если указан SNI — отвечает ли мост сертификатом сайта маскировки.
#       Reality пересылает чужое рукопожатие на сайт маскировки (target),
#       поэтому исправный мост показывает сертификат этого сайта.
#
#  v2 против версии из install-node.sh: различает "мост принял соединение и
#  сразу оборвал" (Reality не дошёл до target — так выглядит неработающий
#  DNS в контейнере или недоступный target) и "мост не отвечает".
#  В файле нет IP, ключей и других секретов.
# =============================================================================
set -uo pipefail
IP="${1:-}"; PORT="${2:-2087}"; SNI="${3:-}"
if [ -z "$IP" ]; then
    echo "Использование: bridge-check <IP_МОСТА> [ПОРТ=2087] [SNI]"
    echo "Запускать на ВХОДЯЩЕЙ ноде."
    exit 2
fi

if timeout 5 bash -c "</dev/tcp/$IP/$PORT" 2>/dev/null; then
    echo "✅ TCP $IP:$PORT открыт с этой ноды"
else
    MY_IP="$(curl -s4 --max-time 5 https://api.ipify.org 2>/dev/null || true)"
    echo "❌ TCP $IP:$PORT закрыт с этой ноды"
    echo "   Чаще всего — файрвол моста. На мосту выполните:"
    echo "     bridge-allow ${MY_IP:-<IP_ЭТОЙ_НОДЫ>}"
    echo "   Список разрешённых: bridge-allow -l"
    echo "   Если IP уже разрешён — проверьте на мосту, что Xray слушает порт: node-check"
    exit 1
fi

if [ -z "$SNI" ]; then
    echo "ℹ️  SNI не указан — маскировка не проверялась. Полная проверка: bridge-check $IP $PORT <SNI>"
    exit 0
fi

OUT="$(curl -vk -m 10 --resolve "$SNI:$PORT:$IP" "https://$SNI:$PORT" 2>&1 || true)"
if grep -q 'subject:' <<< "$OUT"; then
    echo "✅ Мост отвечает сертификатом сайта маскировки:"
    grep -m1 'subject:' <<< "$OUT" | sed 's/^\*[[:space:]]*/   /'
    echo "   Маскировка работает. Если трафик всё равно не идёт — проверьте в панели,"
    echo "   что пользователь моста состоит в скваде с инбаундом моста."
    exit 0
fi

echo "❌ Мост не ответил сертификатом для SNI $SNI"
if grep -qiE 'decode error|unexpected eof|connection reset|wrong version|SSL_ERROR_SYSCALL|Empty reply' <<< "$OUT"; then
    echo "   Мост принял соединение и сразу оборвал его. Так бывает, когда Reality"
    echo "   на мосту не может подключиться к сайту маскировки (target). Проверьте на мосту:"
    echo "     1) curl -sI -m 8 https://$SNI | head -1        — виден ли сайт с сервера;"
    echo "     2) docker exec remnanode getent hosts $SNI    — разрешает ли имя контейнер."
    echo "   Если сайт виден с сервера, а контейнер имя не разрешает — в профиле моста"
    echo "   замените \"target\": \"$SNI:443\" на \"target\": \"<IP_САЙТА>:443\" (serverNames не менять)."
elif grep -qiE 'timed out|timeout' <<< "$OUT"; then
    echo "   Мост не ответил за 10 секунд: рукопожатие теряется по дороге или мост перегружен."
else
    echo "   Причина не распознана. Последние строки ответа:"
    tail -4 <<< "$OUT" | sed 's/^/   /'
fi
echo "   Проверьте также, что SNI совпадает с serverNames инбаунда моста."
exit 1
